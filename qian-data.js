// 获取随机签
function getRandomQian() {
    const keys = Object.keys(qianData);
    const randomKey = keys[Math.floor(Math.random() * keys.length)];
    return qianData[randomKey];
}

// 根据编号获取签
function getQianByNumber(num) {
    return qianData[num] || null;
}
